#!/usr/bin/env bash
# Single-reversal ABCEF plasticity-switch — no-context variant, 1000 trials/phase,
# with B, C, and F stimuli included.
#
# Purpose: disambiguate stimulus-identity from value encoding in TDR/decoders.
#   A: high→low at reversal      B: high→high (stays rewarded, control)
#   C: 50% always (neutral)
#   E: low→high at reversal      F: low→low   (stays unrewarded, control)
#
# The value regressor uses all high/low stimuli (A/B = high pre; E/F = low pre),
# so the value axis captures reward value rather than stim identity. C is neutral
# and sits at the value midpoint.
#
# Task data is auto-generated by ensure_task_data() if not already present:
#   task_data/reversal_abcef_multirev_partial_train2_tpp1000_test2_tpp1000_seed42.pkl
#
# Results:
#   results/22_04_26_singlerev_abcef_bcinc_tpp1000_nocontext/

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
cd "$REPO_ROOT"

# ── No-context (model receives state only, must infer reversal from rewards) ──
# No --task_pkl: ensure_task_data() generates/finds the ABCEF pkl automatically.
# --include_mid_stim adds C to the stimulus set (A, B, C, E, F).
python3 experiment_scripts/run_ace_plasticity_multirun_v2.py \
    --n_runs            10 \
    --n_train_reversals 1 \
    --n_test_reversals  1 \
    --trials_per_phase  1000 \
    --plot_stims        0,1,2,4,5 \
    --include_mid_stim \
    --no_context \
    --results_dir       results/22_04_26_singlerev_abcef_bcinc_tpp1000_nocontext

echo ""
echo "Done. Results in: results/22_04_26_singlerev_abcef_bcinc_tpp1000_nocontext"
